    <section class="job_section">
        <h2 class="heading"> Site Supervisor (RENEWABLE ENERGY)</h2>
        <p>Reference Number: RE026 </p>
        <p>Salary: MYR 3,500 - MYR 5,000 per month </p>
        <p>Position Reports To: Project Manager</p>
        <h3 class="heading">Description:</h3>
        <p>Supervise daily on-site solar engineering installations and civil project milestones. Coordinates subcontractor workflows, enforces workplace health and safety compliance, and reports site performance metrics back to the central tracking network.</p>
        <h3 class="heading">Key Responsibilities:</h3>
        <ul>
            <li>On-Sites Supervision: Oversee day-to-day civil and electrical installation activities of commercial solar photovoltaic (PV) systems</li>
            <li>Safety & Compliance: Enforce workplace health, safety, and environmental protection regulations on-site to maintain zero-incident operations.</li>
            <li>Progress Logging: Record Physical installation milestones and submit field metrics to the corporate operations and maintenance tracking system.</li>
        </ul>
        <h3 class="heading">Essential and Preferable Requirements:</h3>
        <ol>
            <li>Education: Diploma or Bachelor's Degree in Civil Engineering, Electrical Engineering, or a related field.</li>
            <li>Experience: Minimum of 2 years of hands-on experience in on-site construction supervision or solar PV installations.</li>
            <li>Certification: Valid CIDB Green Card for site safety compliance in Malaysia.</li>
            <li>Skills: Strong familiarity with NET Energy Metering (NEM) guidelines and local grid connection regulations.</li>
        </ol>
    </section>

